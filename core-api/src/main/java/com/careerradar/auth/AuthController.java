package com.careerradar.auth;

import com.careerradar.common.security.AppUserProperties;
import com.careerradar.common.security.JwtService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import java.util.Locale;
import org.springframework.security.authentication.BadCredentialsException;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

/**
 * Login for the single configured user. There is no registration: credentials come from
 * {@code APP_USER_EMAIL} and {@code APP_USER_PASSWORD_HASH}.
 */
@RestController
@RequestMapping("/api/v1/auth")
@Tag(name = "auth", description = "Single-user authentication")
public class AuthController {

    private final AppUserProperties user;
    private final PasswordEncoder passwordEncoder;
    private final JwtService jwtService;

    public AuthController(
            AppUserProperties user, PasswordEncoder passwordEncoder, JwtService jwtService) {
        this.user = user;
        this.passwordEncoder = passwordEncoder;
        this.jwtService = jwtService;
        if (isBlank(user.email()) || isBlank(user.passwordHash())) {
            throw new IllegalStateException(
                    "APP_USER_EMAIL and APP_USER_PASSWORD_HASH must be configured.");
        }
        if (!looksLikeBcrypt(user.passwordHash())) {
            throw new IllegalStateException(
                    "APP_USER_PASSWORD_HASH must be a BCrypt hash generated by "
                            + "./gradlew :core-api:hashPassword");
        }
    }

    @PostMapping("/login")
    @Operation(summary = "Exchange email and password for a JWT access token")
    @ApiResponse(responseCode = "200", description = "Credentials accepted")
    @ApiResponse(responseCode = "401", description = "Invalid email or password")
    @ApiResponse(responseCode = "400", description = "Malformed request")
    public LoginResponse login(@Valid @RequestBody LoginRequest request) {
        // Always run BCrypt so a wrong email does not answer faster than a wrong password.
        boolean passwordMatches = passwordEncoder.matches(request.password(), user.passwordHash());
        boolean emailMatches = normalize(user.email()).equals(normalize(request.email()));
        if (!emailMatches || !passwordMatches) {
            throw new BadCredentialsException("Invalid email or password");
        }

        JwtService.IssuedToken issued = jwtService.issue(user.email());
        return new LoginResponse(issued.token(), issued.expiresInSeconds());
    }

    private static String normalize(String value) {
        return value == null ? "" : value.trim().toLowerCase(Locale.ROOT);
    }

    private static boolean isBlank(String value) {
        return value == null || value.isBlank();
    }

    private static boolean looksLikeBcrypt(String hash) {
        return hash.length() == 60
                && (hash.startsWith("$2a$") || hash.startsWith("$2b$") || hash.startsWith("$2y$"));
    }

    @Schema(name = "LoginRequest")
    public record LoginRequest(
            @NotBlank @Email @Size(max = 254) String email,
            @NotBlank @Size(max = 200) String password) {
    }

    @Schema(name = "LoginResponse")
    public record LoginResponse(
            @Schema(description = "HS256 JWT access token", example = "eyJhbGciOiJIUzI1NiJ9...")
            String accessToken,
            @Schema(description = "Token lifetime in seconds", example = "3600")
            long expiresIn) {
    }
}
